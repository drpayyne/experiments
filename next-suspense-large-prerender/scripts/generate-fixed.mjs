import { mkdir, writeFile } from 'node:fs/promises'
import { cases, parseCase } from '../lib/content.js'

for (const slug of cases) {
  const { size, mode } = parseCase(slug)
  const directory = new URL(`../app/fixed/${slug}/`, import.meta.url)
  await mkdir(directory, { recursive: true })
  await writeFile(new URL('page.js', directory), `// Generated by scripts/generate-fixed.mjs; intentionally a literal, non-param route.
import { Scenario } from '../../../lib/content'

export default function Page() {
  return <main><h1>Fixed: ${slug}</h1><Scenario size="${size}" mode="${mode}" /></main>
}
`)
}
